"""Turn module results into plain-language findings from admin-editable templates (FR-58).

Never generated by an LLM: the text is a template filled with computed numbers.
"""

from django.utils import translation
from django.utils.translation import gettext as _

from .formatting import fmt
from .models import FindingTemplate
from .modules import MODULES


class _KeepUnknown(dict):
    """Leave unknown placeholders visible ({name}) rather than failing."""

    def __missing__(self, key):
        return "{" + key + "}"


def render_finding(module_name, rating, results, language):
    template = FindingTemplate.objects.filter(module=module_name, rating=rating).first()
    if template is None:
        return ""
    with translation.override(language):
        values = MODULES[module_name].finding_values(results)
        text = getattr(template, f"text_{language}", "") or template.text
        return text.format_map(_KeepUnknown({k: fmt(v) for k, v in values.items()}))


def unavailable_text(language):
    with translation.override(language):
        return _(
            "This section is unavailable: the data could not be retrieved or analysed. "
            "It does not mean that there is no issue."
        )
